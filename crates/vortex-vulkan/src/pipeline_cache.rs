//! Optional persistent Vulkan pipeline cache for independent synthetic tests.
use ash::vk;
use std::{fs, io::{Read, Write}, path::{Path, PathBuf}};

const MAX_BYTES: usize = 64 * 1024 * 1024;

pub struct Cache<'a> {
    device: &'a ash::Device,
    handle: vk::PipelineCache,
    path: Option<PathBuf>,
}

fn matches_device(data: &[u8], props: &vk::PhysicalDeviceProperties) -> bool {
    if data.len() < 32 { return false; }
    let u32_at = |i: usize| u32::from_le_bytes(data[i..i+4].try_into().unwrap());
    u32_at(0) == 32
        && u32_at(4) == 1
        && u32_at(8) == props.vendor_id
        && u32_at(12) == props.device_id
        && data[16..32] == props.pipeline_cache_uuid
}

fn load(path: &Path, props: &vk::PhysicalDeviceProperties) -> Vec<u8> {
    let file = match fs::File::open(path) {
        Ok(f) => f,
        Err(e) => {
            println!("pipeline cache: cold ({e})");
            return Vec::new();
        }
    };
    let mut bytes = Vec::new();
    if file.take((MAX_BYTES + 1) as u64).read_to_end(&mut bytes).is_err()
        || bytes.len() > MAX_BYTES || !matches_device(&bytes, props)
    {
        println!("pipeline cache: rejected incompatible or oversized file");
        return Vec::new();
    }
    println!("pipeline cache: loaded {} bytes", bytes.len());
    bytes
}

impl<'a> Cache<'a> {
    pub fn open(device: &'a ash::Device, props: &vk::PhysicalDeviceProperties) -> Self {
        let path = std::env::var_os("AMD_VK_PIPELINE_CACHE").map(PathBuf::from);
        let mut handle = vk::PipelineCache::null();
        if let Some(p) = &path {
            let bytes = load(p, props);
            let info = vk::PipelineCacheCreateInfo::default().initial_data(&bytes);
            // Only use local cache files generated by this probe.
            match unsafe { device.create_pipeline_cache(&info, None) } {
                Ok(h) => handle = h,
                Err(e) => println!("pipeline cache: disabled ({e:?})"),
            }
        }
        Self { device, handle, path }
    }

    pub fn handle(&self) -> vk::PipelineCache { self.handle }

    pub fn save(&self) {
        let Some(path) = &self.path else { return };
        if self.handle == vk::PipelineCache::null() { return; }
        match unsafe { self.device.get_pipeline_cache_data(self.handle) } {
            Ok(data) if data.len() <= MAX_BYTES => {
                match save_file(path, &data) {
                    Ok(()) => println!("pipeline cache: saved {} bytes", data.len()),
                    Err(e) => println!("pipeline cache: save failed ({e})"),
                }
            }
            Ok(_) => println!("pipeline cache: too large to save"),
            Err(e) => println!("pipeline cache: read failed ({e:?})"),
        }
    }
}

fn save_file(path: &Path, data: &[u8]) -> std::io::Result<()> {
    let mut name = path.as_os_str().to_owned();
    name.push(format!(".{}.tmp", std::process::id()));
    let temp = PathBuf::from(name);
    let mut file = fs::OpenOptions::new().write(true).create_new(true).open(&temp)?;
    let result = file.write_all(data).and_then(|_| file.sync_all());
    drop(file);
    let result = result.and_then(|_| fs::rename(&temp, path));
    if result.is_err() { let _ = fs::remove_file(&temp); }
    result
}

impl Drop for Cache<'_> {
    fn drop(&mut self) {
        if self.handle != vk::PipelineCache::null() {
            unsafe { self.device.destroy_pipeline_cache(self.handle, None) };
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn rejects_wrong_device_uuid_and_truncated_headers() {
        let mut p = vk::PhysicalDeviceProperties::default();
        p.vendor_id = 0x1002;
        p.device_id = 0x73ff;
        p.pipeline_cache_uuid = [7; 16];
        let mut data = Vec::new();
        for v in [32u32, 1, p.vendor_id, p.device_id] { data.extend(v.to_le_bytes()); }
        data.extend(p.pipeline_cache_uuid);
        assert!(matches_device(&data, &p));
        assert!(!matches_device(&data[..31], &p));
        data[12] ^= 1;
        assert!(!matches_device(&data, &p));
        data[12] ^= 1;
        data[16] ^= 1;
        assert!(!matches_device(&data, &p));
    }
}
